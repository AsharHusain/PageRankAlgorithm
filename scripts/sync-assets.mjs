// BUILD-TIME asset sync -- not the execution path.
//
// Copies c/*.c and outputs/*.txt into src/generated/*.js as exported string
// constants so the UI can DISPLAY them:
//   * the Code tab shows the exact .c sources the backend compiles;
//   * the Archive tab shows the historical terminal capture.
//
// Do not confuse this with how results are produced. Live PageRank results
// come from server/pagerank-service.mjs spawning the compiled binaries at
// request time. This script only moves text around so the browser can read
// it, and nothing it generates is ever presented as a live measurement.
//
// Runs automatically via "postinstall" / "predev" / "prebuild" in package.json.
// Safe to re-run any time: it only reads from c/ and outputs/, and only
// writes into src/generated/.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..');
const OUT_DIR = path.join(ROOT, 'src', 'generated');

fs.mkdirSync(OUT_DIR, { recursive: true });

function copyAsJsModule(srcRelPath, outFileName, varName) {
  const srcPath = path.join(ROOT, srcRelPath);
  const content = fs.readFileSync(srcPath, 'utf8');
  const outPath = path.join(OUT_DIR, outFileName);
  const banner =
    `// AUTO-GENERATED by scripts/sync-assets.mjs -- do not edit by hand.\n` +
    `// Source of truth: ${srcRelPath}\n` +
    `// Regenerated automatically on "npm install" / "npm run dev" / "npm run build".\n\n`;
  const js = `${banner}const ${varName} = ${JSON.stringify(content)};\nexport default ${varName};\n`;
  fs.writeFileSync(outPath, js, 'utf8');
  console.log(`  synced ${srcRelPath} -> src/generated/${outFileName}`);
}

console.log('Syncing generated assets from c/ and outputs/ ...');
copyAsJsModule('c/serial_pagerank.c', 'serialCode.js', 'serialCode');
copyAsJsModule('c/openmp_pagerank.c', 'openmpCode.js', 'openmpCode');
copyAsJsModule('outputs/serial_output.txt', 'serialOutput.js', 'serialOutput');
copyAsJsModule('outputs/openmp_output.txt', 'openmpOutput.js', 'openmpOutput');
console.log('Done.');
